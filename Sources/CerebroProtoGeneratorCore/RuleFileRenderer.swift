/// Writes `ProtoRule.generated` as Swift source.
enum RuleFileRenderer {
    /// Checks every message name against `index`, and fails listing all that match no type.
    static func render(_ map: TrafficMap, index: ProtoTypeIndex) throws -> String {
        let names = map.rules.flatMap { $0.messages.map(\.name) }
        let unknown = names.filter { index.swiftType(for: $0) == nil }
        guard unknown.isEmpty else {
            throw GeneratorError.unknownMessages(Array(Set(unknown)).sorted())
        }
        let entries = map.rules.flatMap { rule in
            rule.messages.map { message in
                entry(rule: rule, direction: message.direction, swiftType: index.swiftType(for: message.name) ?? "")
            }
        }
        return header + (entries.isEmpty ? "    static let generated: [ProtoRule] = []\n" : body(entries)) + "}\n"
    }

    // `ProtoRule` is in `CerebroProto` for SPM and the XCFramework, and in `Cerebro` for the Pod.
    private static let header = """
        // Generated by cerebro-proto-gen from traffic_map.json. Do not edit.
        // swift-format-ignore-file
        // swiftlint:disable all

        import SwiftProtobuf

        #if canImport(CerebroProto)
        import CerebroProto
        #else
        import Cerebro
        #endif

        extension ProtoRule {
            /// The rules from `traffic_map.json`, in file order.

        """

    private static func body(_ entries: [String]) -> String {
        "    static let generated: [ProtoRule] = [\n" + entries.joined() + "    ]\n"
    }

    private static func entry(rule: TrafficMap.Rule, direction: String, swiftType: String) -> String {
        """
                ProtoRule(
                    name: \(optional(rule.name)),
                    match: ProtoRule.Match(host: \(optional(rule.match.host)), path: \(optional(rule.match.path)), \
        pathPrefix: \(optional(rule.match.pathPrefix)), regex: \(optional(rule.match.regex))),
                    methods: [\((rule.methods ?? []).map(literal).joined(separator: ", "))],
                    direction: .\(direction),
                    messageType: \(swiftType).self,
                    stripPrefixBytes: \(rule.framing?.stripPrefixBytes ?? 0),
                    source: .file
                ),

        """
    }

    private static func optional(_ value: String?) -> String {
        value.map(literal) ?? "nil"
    }

    /// A Swift string literal, with quotes and backslashes in a name or regex escaped.
    private static func literal(_ value: String) -> String {
        String(reflecting: value)
    }
}
